#!/usr/bin/env node
// Builds the canonical SVG registry.
//   node scripts/build.mjs          optimise sources in place + write src/generated/registry.ts
//   node scripts/build.mjs --check  fail if sources are not optimised / registry is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from './lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = path.join(root, 'svg');
const outFile = path.join(root, 'src', 'generated', 'registry.ts');
const check = process.argv.includes('--check');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith('.svg') ? [path.join(dir, e.name)] : [],
  );
}

const files = walk(svgDir).sort();
const entries = [];
let stale = false;
let totalBytes = 0;

for (const file of files) {
  const name = path.relative(svgDir, file).replace(/\\/g, '/').replace(/\.svg$/, '');
  const source = fs.readFileSync(file, 'utf8');
  const { optimized, def } = compile(name, source);
  totalBytes += Buffer.byteLength(optimized);
  if (optimized.trim() !== source.trim()) {
    if (check) { console.error(`not optimised: ${name}`); stale = true; }
    else fs.writeFileSync(file, optimized + '\n');
  }
  entries.push([name, def]);
}

const names = entries.map(([n]) => `  | '${n}'`).join('\n');
const body = entries.map(([n, d]) => `  '${n}': ${JSON.stringify(d)},`).join('\n');
const out = `// AUTO-GENERATED by packages/assets/scripts/build.mjs - do not edit by hand.
// Source of truth: packages/assets/svg/**/*.svg
import type { AssetDef } from '../types';

export type AssetName =
${names};

export const registry: Record<AssetName, AssetDef> = {
${body}
};
`;

if (check) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== out) { console.error('registry.ts is stale - run `npm run build --workspace=@padhai-pilot/assets`'); stale = true; }
  if (stale) process.exit(1);
  console.log(`ok: ${entries.length} assets, ${totalBytes} bytes`);
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, out);
  console.log(`built ${entries.length} assets (${totalBytes} bytes of optimised SVG) -> src/generated/registry.ts`);
}
